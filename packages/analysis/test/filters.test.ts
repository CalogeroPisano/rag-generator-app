import { describe, expect, it } from "vitest"
import { classifyDirectory, classifyFileContent, classifyFilePath } from "../src/filters.ts"
import { detectLanguage } from "../src/languages.ts"
import { sanitizeArchivePath } from "../src/paths.ts"
import { defaultLimits } from "../src/limits.ts"
import { prepareFile } from "../src/prepare.ts"

const encode = (text: string) => new TextEncoder().encode(text)

describe("sanitizeArchivePath", () => {
  it.each([
    ["../etc/passwd"],
    ["a/../../b"],
    ["/etc/passwd"],
    ["C:\\Windows\\system32"],
    ["..\\..\\evil.txt"],
    ["a\0b"],
    ["./"]
  ])("rejects %j", (name) => {
    expect(sanitizeArchivePath(name)).toBeUndefined()
  })

  it("normalises separators and dot segments", () => {
    expect(sanitizeArchivePath("src\\app/./main.ts")).toBe("src/app/main.ts")
  })
})

describe("classification", () => {
  it("excludes dependency, build and vcs directories", () => {
    expect(classifyDirectory("node_modules")).toBe("dependency")
    expect(classifyDirectory("dist")).toBe("build_output")
    expect(classifyDirectory(".git")).toBe("vcs")
    expect(classifyDirectory("src")).toBeUndefined()
  })

  it("classifies files by path", () => {
    expect(classifyFilePath("pnpm-lock.yaml")).toBe("lockfile")
    expect(classifyFilePath("public/app.min.js")).toBe("minified")
    expect(classifyFilePath("app.js.map")).toBe("source_map")
    expect(classifyFilePath("src/routeTree.gen.ts")).toBe("generated")
    expect(classifyFilePath("Form1.Designer.cs")).toBe("generated")
    expect(classifyFilePath("logo.png")).toBe("binary")
    expect(classifyFilePath(".env")).toBe("sensitive_file")
    expect(classifyFilePath("config/.env.production")).toBe("sensitive_file")
    expect(classifyFilePath(".env.example")).toBeUndefined()
    expect(classifyFilePath("certs/server.key")).toBe("sensitive_file")
    expect(classifyFilePath("src/main.ts")).toBeUndefined()
  })

  it("classifies files by content", () => {
    expect(classifyFileContent("data.txt", new Uint8Array([65, 0, 66]))).toBe("binary")
    expect(classifyFileContent("api.ts", encode("// Code generated by protoc. DO NOT EDIT.\nexport {}"))).toBe(
      "generated"
    )
    expect(classifyFileContent("bundle.js", encode(`var a=1;${"b();".repeat(1000)}`))).toBe("minified")
    expect(classifyFileContent("main.ts", encode("export const a = 1\n"))).toBeUndefined()
  })

  it("detects languages", () => {
    expect(detectLanguage("src/App.tsx")).toBe("typescript")
    expect(detectLanguage("Program.cs")).toBe("csharp")
    expect(detectLanguage("docker/Dockerfile")).toBe("dockerfile")
    expect(detectLanguage("README")).toBe("plaintext")
  })
})

describe("prepareFile", () => {
  it("masks content and keeps metadata", () => {
    const file = prepareFile("src/config.ts", encode(`export const apiKey = "AKIAIOSFODNN7EXAMPLE"\n`), defaultLimits)
    expect(file.excluded).toBeUndefined()
    expect(file.content).toContain("[REDACTED:aws-access-key-id]")
    expect(file.secrets).toEqual([{ rule: "aws-access-key-id", line: 1 }])
    expect(file.contentHash).toMatch(/^[0-9a-f]{64}$/)
    expect(file.language).toBe("typescript")
  })

  it("decodes Windows-1252 files", () => {
    const bytes = new Uint8Array([...encode("// perch"), 0xe8, 10])
    const file = prepareFile("legacy.java", bytes, defaultLimits)
    expect(file.encoding).toBe("windows-1252")
    expect(file.content).toBe("// perchè\n")
  })

  it("keeps oversized files as metadata only", () => {
    const file = prepareFile("big.ts", new Uint8Array(10), { ...defaultLimits, maxFileBytes: 5 })
    expect(file.excluded).toBe("too_large")
    expect(file.content).toBeUndefined()
  })
})
