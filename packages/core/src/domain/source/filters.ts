/** Classifies a directory by name; excluded directories are not descended into. */
export const classifyDirectory = (name: string): ExclusionReason | undefined => {
  for (const [reason, names] of directoryRules) {
    if (names.has(name)) return reason
  }
  if (name.startsWith("cmake-build-")) return "build_output"
  return undefined
}

