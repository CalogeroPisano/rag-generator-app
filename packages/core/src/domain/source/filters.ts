const extensionOf = (fileName: string): string => {
  const dot = fileName.lastIndexOf(".")
  return dot > 0 ? fileName.slice(dot + 1).toLowerCase() : ""
}

const baseName = (path: string): string => path.slice(path.lastIndexOf("/") + 1)

/** Classifies a file using only its path. */
export const classifyFilePath = (path: string): ExclusionReason | undefined => {
  const name = baseName(path)
  const lower = name.toLowerCase()
  const extension = extensionOf(name)

  if (lower === ".env" || (lower.startsWith(".env.") && !envTemplates.has(lower))) return "sensitive_file"
  if (sensitiveNames.has(lower) || sensitiveExtensions.has(extension)) return "sensitive_file"
  if (lockfiles.has(name)) return "lockfile"
  if (lower.endsWith(".map")) return "source_map"
  if (/[.-]min\.(m?js|cjs|css)$/.test(lower)) return "minified"
  if (lower.includes(".generated.") || generatedSuffixes.some((suffix) => lower.endsWith(suffix))) return "generated"
  if (binaryExtensions.has(extension)) return "binary"
  return undefined
}

const generatedMarkers =
  /@generated|<auto-generated|code generated by|do not edit|this file (?:was|is) (?:automatically|auto-?) ?generated|autogenerated by/i

/** Classifies a file using its content. `bytes` is the full file content. */
export const classifyFileContent = (path: string, bytes: Uint8Array): ExclusionReason | undefined => {
  const sniffLength = Math.min(bytes.length, 8000)
  for (let i = 0; i < sniffLength; i++) {
    if (bytes[i] === 0) return "binary"
  }

  const head = new TextDecoder("utf-8", { fatal: false }).decode(bytes.subarray(0, 2048))
  if (generatedMarkers.test(head)) return "generated"

  if (/\.(m?js|cjs|css)$/i.test(path) && bytes.length > 2000) {
    const text = new TextDecoder("utf-8", { fatal: false }).decode(bytes)
    const lines = text.split("\n")
    const longest = lines.reduce((max, line) => Math.max(max, line.length), 0)
    if (longest > 1000 && text.length / lines.length > 300) return "minified"
  }
  return undefined
}
